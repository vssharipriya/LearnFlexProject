const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const manager = fs.readFileSync(path.join(root, 'offline-manager.js'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const app = fs.readFileSync(path.join(root, 'app.js'), 'utf8');
const auth = fs.readFileSync(path.join(root, 'app-enhancements.js'), 'utf8');
assert.match(manager, /indexedDB\.open\(DB_NAME, DB_VERSION\)/, 'offline data must use IndexedDB');
assert.match(manager, /storePut\('outbox', \{ id: OUTBOX_KEY/, 'progress must be queued in a durable outbox');
assert.match(manager, /storePut\('packs', \{ id, \.\.\.payload/, 'offline packs must be stored separately');
assert.match(manager, /learnFlexOffline|downloadAllSubjects/, 'subject download controls must be implemented');
assert.match(manager, /2 \*\* Math\.min\(retryCount - 1, 5\)/, 'failed sync must use bounded exponential retry');
assert.match(manager, /AbortController/, 'poor network requests must time out');
assert.match(manager, /learnflex-progress-sync/, 'background sync must be registered where supported');
assert.match(manager, /addEventListener\('online'/, 'reconnect must trigger sync');
assert.match(manager, /pagehide/, 'progress snapshot must be attempted on page close');
assert.match(manager, /local-state-backup/, 'IndexedDB must keep a restorable local progress backup');
assert.match(manager, /learnflex_access_user.*currentUser\.id/, 'offline sync must only use the matching learner token');
assert.match(auth, /previousTokenUser!==id/, 'offline login must not discard the same learner session token');
assert.match(sw, /offline-manager\.js/, 'offline manager must be in the cached application shell');
assert.match(sw, /learnflex-progress-sync/, 'service worker must handle background sync wake-up');
assert.match(sw, /if\(url\.pathname\.startsWith\('\/api\/'\)\)return/, 'authenticated API responses must not be cached');
assert.match(html, /offline-manager\.js/, 'offline manager must be loaded by the app');
assert.match(app, /localStorage\.setItem\(STORE_KEY/, 'existing local progress persistence remains in place');
console.log('✓ offline acceptance contracts: IndexedDB packs/outbox, reconnect retry, poor-network timeout, service-worker shell cache, API privacy');
